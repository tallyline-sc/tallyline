//! Resolved design-system colour tokens generated from `ui/design-tokens/`.

use egui::Color32;

/// Resolved colours for one Tallyline theme.
#[derive(Clone, Copy, Debug)]
pub struct ThemeColors {
    values: &'static [(&'static str, [u8; 4])],
}

impl ThemeColors {
    /// Look up a resolved colour token.
    #[must_use]
    pub fn color(&self, name: &str) -> Option<Color32> {
        self.values
            .iter()
            .find(|(key, _)| *key == name)
            .map(|(_, rgba)| Color32::from_rgba_unmultiplied(rgba[0], rgba[1], rgba[2], rgba[3]))
    }
}

